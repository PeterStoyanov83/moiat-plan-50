def determine_profile(response):
    if response.movement_level == 'ниско' and response.energy_level in (1, 2):
        return PROFILE_LEK_START
    if response.main_goal == 'отслабване':
        return PROFILE_OTSLABVANE
    if response.main_goal == 'енергия':
        return PROFILE_ENERGIYA
    if response.social_activity == 'ниска':
        return PROFILE_SOCIALEN
    return PROFILE_BALANS


